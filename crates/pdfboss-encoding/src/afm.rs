//! Standard-14 advance-width tables, from the public Adobe Core-14
//! AFM metrics (see ISO 32000-1 Annex D / Adobe's PDF Reference for the
//! standard-14 font names). Widths are in the 1000-unit glyph space
//! used throughout PDF (ISO 32000-1 9.2.4), i.e. thousandths of the
//! font's em square; multiply by `font_size / 1000` for text space.
//!
//! These tables back [`standard_14_width`], used as a fallback advance
//! when a PDF's `/Widths` array is absent or incomplete and the font
//! program itself isn't embedded (font substitution).

/// Strips a PDF font-subset tag (`ISO 32000-1` 9.6.4: six uppercase
/// letters followed by `+`, e.g. `ABCDEF+Times-Bold`) from `base_font`.
///
/// Covers ISO 32000-1 §9.6.4.
fn strip_subset_prefix(base_font: &str) -> &str {
    let bytes = base_font.as_bytes();
    // `> 7`, not `> 6`: the guard must require at least one character after
    // the `+` for the strip to be meaningful, so the degenerate
    // `"ABCDEF+"` (len 7) is left unstripped instead of yielding an empty
    // name. Matches `substitute.rs`'s `strip_subset_prefix` guard exactly.
    if bytes.len() > 7 && bytes[6] == b'+' && bytes[..6].iter().all(u8::is_ascii_uppercase) {
        &base_font[7..]
    } else {
        base_font
    }
}

/// A standard-14 font family (weight/slant resolved separately).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Family {
    Helvetica,
    Times,
    Courier,
}

/// Recognized family stems, longest first. Ordering matters: a shorter
/// stem that is itself a prefix of a longer one (`times` vs.
/// `timesnewroman` vs. `timesnewromanps`, `courier` vs. `couriernew`)
/// must never shadow the more specific match, or the leftover
/// remainder handed to [`strip_style_tokens`] would contain stem
/// characters instead of style/noise ones. `classify` walks this list
/// in order and takes the first hit.
const FAMILY_STEMS: &[(&str, Family)] = &[
    ("timesnewromanps", Family::Times),
    ("timesnewroman", Family::Times),
    ("couriernew", Family::Courier),
    ("helvetica", Family::Helvetica),
    ("courier", Family::Courier),
    ("arial", Family::Helvetica),
    ("times", Family::Times),
];

/// Style/noise tokens recognized after the family stem, longest first
/// (so, e.g., `psmt` is tried whole rather than stopping at `ps`).
/// `mt`/`ps`/`psmt` are TrueType-alias noise suffixes (`Arial-BoldMT`,
/// `TimesNewRomanPSMT`). Anything left over after greedily stripping
/// these tokens means the name carries a real, metrically distinct
/// qualifier (`Narrow`, `Neue`, `Condensed`, `Light`, `Ten`, ...) and
/// so isn't one of the standard 14.
const STYLE_TOKENS: &[&str] = &[
    "oblique", "regular", "italic", "roman", "bold", "book", "psmt", "ps", "mt",
];

/// Greedily strips [`STYLE_TOKENS`] from the front of `rest`, folding
/// them into `(bold, italic)` flags, until `rest` is fully consumed.
/// Returns `None` the moment a prefix token isn't recognized, i.e. the
/// name has a qualifier this module doesn't tabulate.
fn strip_style_tokens(mut rest: &str) -> Option<(bool, bool)> {
    let mut bold = false;
    let mut italic = false;
    while !rest.is_empty() {
        let tok = *STYLE_TOKENS.iter().find(|&&t| rest.starts_with(t))?;
        match tok {
            "bold" => bold = true,
            "italic" | "oblique" => italic = true,
            _ => {}
        }
        rest = &rest[tok.len()..];
    }
    Some((bold, italic))
}

/// Classifies a (subset-prefix-stripped) `/BaseFont` name into a
/// standard-14 family plus bold/italic flags. The name is lowercased
/// and separator-stripped (`-`, `,`, space) before matching, so
/// `Arial-BoldMT`, `arial-bold`, and `Arial,Bold` all resolve alike.
/// The (separator-stripped) name must then start with one of the
/// [`FAMILY_STEMS`] (recognizing the common PostScript and TrueType
/// aliases: `Arial` -> Helvetica, `TimesNewRoman`/`TimesNewRomanPS` ->
/// Times, `CourierNew` -> Courier), and everything after the stem must
/// fully reduce to [`STYLE_TOKENS`] noise.
///
/// This is deliberately strict: a font that merely shares a standard-14
/// prefix but is metrically distinct — `Helvetica-Narrow`, `Helvetica
/// Neue`, `HelveticaNeue-Bold`, `TimesTen-Bold`, `Helvetica-Light`,
/// `Times New Roman Condensed` — leaves an unrecognized token after the
/// stem and so classifies as `None`, same as Symbol, ZapfDingbats, or
/// any other name that isn't one of the standard 14. Returning `None`
/// here is correct even though it's plausible-looking: the caller then
/// falls back to the substitute face's own `hmtx` widths rather than a
/// wrong Core-14 advance.
fn classify(base_font: &str) -> Option<(Family, bool, bool)> {
    let stripped = strip_subset_prefix(base_font);
    let lower = stripped.to_lowercase();
    let compact: String = lower
        .chars()
        .filter(|c| !matches!(c, '-' | ',' | ' '))
        .collect();
    let (family, rest) = FAMILY_STEMS
        .iter()
        .find_map(|&(stem, family)| compact.strip_prefix(stem).map(|rest| (family, rest)))?;
    let (bold, italic) = strip_style_tokens(rest)?;
    Some((family, bold, italic))
}

/// Binary-searches a `(glyph_name, width)` table sorted by name.
fn lookup(table: &[(&str, u16)], glyph_name: &str) -> Option<f32> {
    table
        .binary_search_by_key(&glyph_name, |&(name, _)| name)
        .ok()
        .map(|i| table[i].1 as f32)
}

/// The advance width (1000-unit glyph space) of `glyph_name` in the
/// standard-14 font whose PDF `/BaseFont` (or a recognized alias, or a
/// subsetted variant) is `base_font`, or `None` if `base_font` isn't one
/// of the standard 14 or `glyph_name` is unknown to that font. Symbol and
/// ZapfDingbats match only by their exact names, with no aliases, and take
/// the glyph names of their built-in encodings (Annex D.5 and D.6).
/// Courier's four variants are monospaced (every glyph is 600 units wide
/// per the Adobe Core-14 AFM metrics) and so always return `Some(600.0)`.
/// Oblique variants share their upright counterpart's widths (Helvetica
/// and Helvetica-Oblique are metrically identical, likewise the bold
/// pair), so only upright/bold tables are stored.
///
/// Covers ISO 32000-1 §9.6.2.2.
pub fn standard_14_width(base_font: &str, glyph_name: &str) -> Option<f32> {
    if let Some(table) = symbolic_table(base_font) {
        return lookup(table, glyph_name);
    }
    let (family, bold, italic) = classify(base_font)?;
    match family {
        Family::Courier => Some(600.0),
        Family::Helvetica => {
            let table = if bold { HELVETICA_BOLD } else { HELVETICA };
            lookup(table, glyph_name)
        }
        Family::Times => {
            let table = match (bold, italic) {
                (true, true) => TIMES_BOLD_ITALIC,
                (true, false) => TIMES_BOLD,
                (false, true) => TIMES_ITALIC,
                (false, false) => TIMES_ROMAN,
            };
            lookup(table, glyph_name)
        }
    }
}

/// The width table of Symbol or ZapfDingbats when `base_font`, after
/// subset-prefix stripping, is exactly that name.
fn symbolic_table(base_font: &str) -> Option<&'static [(&'static str, u16)]> {
    match strip_subset_prefix(base_font) {
        "Symbol" => Some(SYMBOL),
        "ZapfDingbats" => Some(ZAPF_DINGBATS),
        _ => None,
    }
}

/// Whether `base_font` (after subset-prefix stripping and alias
/// normalization) names one of the twelve standard-14 text faces. Symbol
/// and ZapfDingbats are symbolic fonts with their own built-in encodings
/// and are not included.
///
/// Covers ISO 32000-1 §9.6.2.2.
pub fn is_standard_14(base_font: &str) -> bool {
    classify(base_font).is_some()
}

